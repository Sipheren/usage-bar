import Foundation

/// Builds `expected.json`, the answer sheet for a fixtures folder: what the macOS core computes from the
/// fixture responses and logs at a fixed time, time zone and exchange rate. Another platform's port runs
/// its own code on the same files and compares. Reads only the folder it is given; makes no requests.
///
/// Folder layout: `api/oauth-usage.json`, `api/oauth-profile.json`, `api/claude-ai-organizations.json`,
/// `api/claude-ai-org-usage.json`, `api/error-401.json`, `api/error-403-scope.json`,
/// `api/cloudflare-challenge.html`, and `claude-code-logs/projects/**/*.jsonl`. Missing files are noted.
public enum ParitySheet {
    public static let now = FixtureAnonymizer.now
    public static let timeZoneID = "Australia/Brisbane"
    /// A made-up fixed rate, so the AUD figures never depend on the day the sheet was made.
    public static let audPerUSD = 1.5

    public static func build(fixtures dir: URL) -> JSONValue {
        let tz = TimeZone(identifier: timeZoneID)!
        func file(_ name: String) -> Data? { try? Data(contentsOf: dir.appendingPathComponent(name)) }

        let profile = file("api/oauth-profile.json").flatMap(Profile.decode)
        let orgs = file("api/claude-ai-organizations.json").map(ClaudeAiCookieClient.parseOrganizations)
        let personalSnap = file("api/oauth-usage.json").flatMap { try? UsageDecoder.decode($0, fetchedAt: now) }
        let workSnap = file("api/claude-ai-org-usage.json").flatMap { try? UsageDecoder.decode($0, fetchedAt: now) }

        var work = account(tag: "W", name: "Work", file: "api/claude-ai-org-usage.json", snapshot: workSnap, tz: tz)
        if case .object(var members) = work {
            var org: [JSONMember] = [m("file", .string("api/claude-ai-organizations.json"))]
            if let orgs {
                let picked = ClaudeAiCookieClient.pickOrg(orgs: orgs, lastActiveOrg: nil)
                org += [
                    m("count", int(orgs.count)),
                    m("pickedWithoutLastActiveOrg", picked.map { p in
                        .object([m("uuid", .string(p.uuid)), m("name", str(p.name))])
                    } ?? .null),
                ]
            } else {
                org.append(m("missing", .bool(true)))
            }
            members.insert(m("organizations", .object(org)), at: 3)
            work = .object(members)
        }

        return .object([
            m("about", .string("Answer sheet for this fixtures folder, generated by the macOS core (ParitySheet.swift). "
                               + "A port must produce the same values from the same files.")),
            m("now", .string("2026-03-02T05:00:00Z")),
            m("timeZone", .string(timeZoneID)),
            m("audPerUSD", .number(String(audPerUSD))),
            m("profile", profile.map { p in
                .object([m("file", .string("api/oauth-profile.json")), m("email", str(p.email)),
                         m("displayName", str(p.displayName)), m("accountUuid", str(p.accountUuid)),
                         m("organizationUuid", str(p.organizationUuid)), m("organizationName", str(p.organizationName)),
                         m("organizationType", str(p.organizationType)), m("rateLimitTier", str(p.rateLimitTier))])
            } ?? .null),
            m("accounts", .array([account(tag: "P", name: "Personal", file: "api/oauth-usage.json",
                                          snapshot: personalSnap, tz: tz), work])),
            m("menuBar", menuBar(personal: personalSnap, work: workSnap)),
            m("cost", cost(root: dir.appendingPathComponent("claude-code-logs/projects"), tz: tz)),
            m("errors", errors(dir: dir, tz: tz)),
        ])
    }

    // MARK: Sections

    static func account(tag: String, name: String, file: String, snapshot: UsageSnapshot?, tz: TimeZone) -> JSONValue {
        guard let snap = snapshot else {
            return .object([m("tag", .string(tag)), m("name", .string(name)), m("file", .string(file)), m("missing", .bool(true))])
        }
        let limits: [JSONValue] = snap.ordered.map { l in
            let d = LimitDisplay(l, now: now, timeZone: tz)
            let pace = l.resetsAt.map { Pace.compute(used: l.percent, resetsAt: $0, windowMinutes: l.windowMinutes, now: now) }
            let status: JSONValue = pace.map { p in
                switch p.status {
                case .onPace: return .string("onPace")
                case .under: return .string("under")
                case .over: return .string("over")
                }
            } ?? .null
            return .object([
                m("name", .string(l.name)),
                m("percent", num(l.percent, 1)),
                m("percentText", .string(d.percentText)),
                m("resetsAt", l.resetsAt.map { .string(iso($0)) } ?? .null),
                m("resetText", str(d.compactTrailing)),
                m("resetTextLarge", str(d.largeTrailing)),
                m("paceText", str(d.paceLine)),
                m("paceStatus", status),
                m("expectedPercent", pace.map { num($0.expected, 2) } ?? .null),
                m("tickFraction", d.tickFraction.map { num($0, 4) } ?? .null),
                // Rounded to 10 minutes, as the text shows it, so ports don't disagree on seconds.
                m("runOutRounded", pace?.runOut.map { .string(iso(Date(timeIntervalSince1970: ($0.timeIntervalSince1970 / 600).rounded() * 600))) } ?? .null),
                m("runOutText", pace?.runOut.map { .string(Formatters.runOutTime($0, now: now, timeZone: tz)) } ?? .null),
            ])
        }
        return .object([
            m("tag", .string(tag)), m("name", .string(name)), m("file", .string(file)),
            m("limits", .array(limits)),
            m("extraUsage", snap.extra.flatMap(Formatters.extraUsageLine).map(JSONValue.string) ?? .null),
        ])
    }

    static func menuBar(personal: UsageSnapshot?, work: UsageSnapshot?) -> JSONValue {
        let inputs = [MenuBarInput(tag: "P", snapshot: personal, lastSuccess: now),
                      MenuBarInput(tag: "W", snapshot: work, lastSuccess: now)]
        func text(_ style: MenuBarStyle, _ metrics: MetricSelection) -> JSONValue {
            .string(MenuBarModel.build(inputs: inputs, style: style, metrics: metrics, now: now).plainText)
        }
        let defaults = MetricSelection()
        let all = MetricSelection(session: true, weekly: true, scoped: true)
        return .object([
            m("note", .string("Plain-text form of the label (MenuBarModel.plainText). Bars list each account's bar "
                              + "values in [ ]. Default metrics: session and weekly; 'withModelWeekly' adds the "
                              + "highest model-scoped weekly.")),
            m("bars", text(.miniBars, defaults)),
            m("percentages", text(.withPercent, defaults)),
            m("compact", text(.compact, defaults)),
            m("iconOnly", text(.iconOnly, defaults)),
            m("barsWithModelWeekly", text(.miniBars, all)),
            m("percentagesWithModelWeekly", text(.withPercent, all)),
        ])
    }

    static func cost(root: URL, tz: TimeZone) -> JSONValue {
        guard FileManager.default.fileExists(atPath: root.path) else {
            return .object([m("logsRoot", .string("claude-code-logs/projects")), m("missing", .bool(true))])
        }
        let scanner = CostScanner(root: root, timeZone: tz)
        let stats = scanner.scan(now: now)
        let s = scanner.summary(now: now)
        let rates = ExchangeRates(rates: ["USD": 1, "AUD": audPerUSD], asOf: now, fetchedAt: now)
        func money(_ usd: Double) -> [JSONMember] {
            let aud = Currency.convert(usd: usd, to: "AUD", rates: rates) ?? 0
            return [m("usd", num(usd, 6)), m("aud", num(aud, 6)),
                    m("usdText", .string(Currency.format(usd, code: "USD"))),
                    m("audText", .string(Currency.format(aud, code: "AUD")))]
        }
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = tz
        let df = DateFormatter()
        df.locale = Locale(identifier: "en_US_POSIX")
        df.timeZone = tz
        df.dateFormat = "yyyy-MM-dd"
        var days: [JSONValue] = []
        for offset in 0..<30 where s.dailyTokens[offset] > 0 || s.dailyUSD[offset] > 0 {
            let date = cal.date(byAdding: .day, value: offset - 29, to: now)!
            days.append(.object([m("date", .string(df.string(from: date)))] + money(s.dailyUSD[offset])
                                + [m("tokens", int(s.dailyTokens[offset]))]))
        }
        let models: [JSONValue] = s.perModel.map { mc in
            let pricing: String
            switch mc.match {
            case .exact(let k): pricing = "exact:" + k
            case .family(let k): pricing = "family:" + k
            case .unpriced: pricing = "unpriced"
            }
            return .object([m("model", .string(mc.model)), m("tokens", int(mc.tokens))] + money(mc.usd)
                           + [m("pricing", .string(pricing))])
        }
        return .object([
            m("logsRoot", .string("claude-code-logs/projects")),
            m("dedup", .object([
                m("jsonlFiles", int(stats.filesRead)),
                m("linesRead", int(stats.linesDecoded)),
                m("usageRecords", int(stats.recordsMerged)),
                m("uniqueMessages", int(stats.uniqueKeys)),
                m("duplicatesCollapsed", int(stats.recordsMerged - stats.uniqueKeys)),
                m("crossFileDuplicateKeys", int(stats.crossFileDuplicateKeys)),
            ])),
            m("days", .array(days)),
            m("today", .object(money(s.todayUSD) + [m("tokens", int(s.todayTokens)),
                                                     m("tokensText", .string(Formatters.tokens(s.todayTokens)))])),
            m("last30Days", .object(money(s.last30USD) + [m("tokens", int(s.last30Tokens)),
                                                           m("tokensText", .string(Formatters.tokens(s.last30Tokens)))])),
            m("byModel", .array(models)),
            m("topModel", str(s.topModel)),
            m("unpricedModels", .array(s.unpricedModels.map(JSONValue.string))),
        ])
    }

    static func errors(dir: URL, tz: TimeZone) -> JSONValue {
        func file(_ name: String) -> Data? { try? Data(contentsOf: dir.appendingPathComponent(name)) }
        func response(_ status: Int, _ headers: [String: String] = [:]) -> HTTPURLResponse {
            HTTPURLResponse(url: URL(string: "https://claude.ai/api/organizations")!, statusCode: status,
                            httpVersion: "HTTP/1.1", headerFields: headers)!
        }
        let until = now.addingTimeInterval(120)
        var out: [JSONMember] = [
            m("retryAfterSeconds", .object([
                m("120", UsageClient.retryAfter("120", now: now).map { num($0, 0) } ?? .null),
                m("Mon, 02 Mar 2026 05:02:00 GMT", UsageClient.retryAfter("Mon, 02 Mar 2026 05:02:00 GMT", now: now)
                    .map { num($0, 0) } ?? .null),
                m("missing (wait 5 minutes)", .null),
            ])),
            m("rateLimitedWithNumbers", str(AccountPresentation(issue: .rateLimited(until: until), hasData: true,
                                                                timeZone: tz).headerNote)),
            m("rateLimitedWithoutNumbers", .string(AccountIssue.rateLimited(until: until).message(timeZone: tz))),
        ]
        if let body = file("api/error-401.json") {
            out.append(m("error401", .object([
                m("isScopeError", .bool(UsageClient.isScopeError(body))),
                m("claudeCodeMessage", .string("Claude Code login rejected — run `claude` once")),
            ])))
        }
        if let body = file("api/error-403-scope.json") {
            out.append(m("error403Scope", .object([
                m("isScopeError", .bool(UsageClient.isScopeError(body))),
                m("message", .string(AccountIssue.scope.message(timeZone: tz))),
            ])))
        }
        if let html = file("api/cloudflare-challenge.html") {
            out.append(m("cloudflare", .object([
                m("status503Body", .bool(ClaudeAiCookieClient.isCloudflareChallenge(response(503), body: html))),
                m("cfMitigatedHeader", .bool(ClaudeAiCookieClient.isCloudflareChallenge(
                    response(200, ["cf-mitigated": "challenge"]), body: Data()))),
                m("status200Body", .bool(ClaudeAiCookieClient.isCloudflareChallenge(response(200), body: html))),
                m("message", .string(AccountIssue.cloudflareChallenge.message(timeZone: tz))),
            ])))
        }
        return .object(out)
    }

    // MARK: Helpers

    static func m(_ key: String, _ value: JSONValue) -> JSONMember { JSONMember(key: key, value: value) }
    static func str(_ s: String?) -> JSONValue { s.map(JSONValue.string) ?? .null }
    static func int<T: BinaryInteger>(_ v: T) -> JSONValue { .number(String(v)) }
    static func num(_ v: Double, _ digits: Int) -> JSONValue { .number(String(format: "%.\(digits)f", v)) }

    static func iso(_ d: Date) -> String {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime]
        f.timeZone = TimeZone(identifier: "UTC")
        return f.string(from: d)
    }
}
